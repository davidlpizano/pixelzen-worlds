"""Sprites pixel art realistas de Noah y Maggie (escala nativa 1x1) para Salon de Noah y Maggie."""
from pz_lib import hx, mix


def _tinte_fase(hexc, fase):
    r, g, b = hx(hexc)
    es_contorno = (r + g + b) < 110
    es_ambar = (r > 180 and r - b > 100 and g > 90)
    if fase == 'dia':
        return (r, g, b)
    if fase == 'dorado':
        if es_contorno:
            return mix((r, g, b), "#241610", 0.25)
        if es_ambar:
            return mix((r, g, b), "#fde047", 0.14)
        if r + g + b > 600:
            return mix((r, g, b), "#fef3c7", 0.16)
        return mix((r, g, b), "#e0822a", 0.16)
    if es_contorno:
        return mix((r, g, b), "#0b1120", 0.45)
    if es_ambar:
        return mix((r, g, b), "#1e293b", 0.10)
    return mix((r, g, b), "#101e38", 0.38)


def draw_sprite_1x(lz, cx, by, sprite_def, fase="dia", shadow_col="#12141c", shadow_alpha=0.36):
    """Dibuja un sprite pixel-art 1x1 centrado horizontalmente en cx y apoyado en y=by."""
    pal_raw, grid = sprite_def
    h = len(grid)
    w = len(grid[0]) if h else 0
    x0 = int(cx - w // 2)
    y0 = int(by - h + 1)
    pal = {ch: _tinte_fase(col, fase) for ch, col in pal_raw.items()}
    if shadow_col:
        s_start = max(0, int(h * 0.78))
        for ry in range(s_start, h):
            py = y0 + ry
            for rx, ch in enumerate(grid[ry]):
                if ch != '.':
                    px = x0 + rx
                    lz.over(px + 1, py + 2, shadow_col, shadow_alpha)
                    lz.over(px, py + 2, shadow_col, shadow_alpha * 0.75)
    for ry, row in enumerate(grid):
        py = y0 + ry
        for rx, ch in enumerate(row):
            if ch == '.':
                continue
            col = pal.get(ch)
            if col is not None:
                lz.put(x0 + rx, py, col)
    return x0, y0

